import { useEffect, type RefObject } from 'react'

/** Close a menu on a pointer down outside `ref` and on Escape (focus goes back to the trigger). */
export function useDismiss(open: boolean, ref: RefObject<HTMLElement | null>, close: () => void, triggerRef: RefObject<HTMLElement | null>) {
  useEffect(() => {
    if (!open) return
    const onDown = (e: PointerEvent) => {
      if (ref.current && !ref.current.contains(e.target as Node)) close()
    }
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        close()
        triggerRef.current?.focus()
      }
    }
    document.addEventListener('pointerdown', onDown)
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('pointerdown', onDown)
      document.removeEventListener('keydown', onKey)
    }
  }, [open])
}
